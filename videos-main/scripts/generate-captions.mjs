#!/usr/bin/env node
// Generates assets/captions-data.js — word-level caption timings for
// compositions/captions.html.
//
// Transcribes each VO clip (whisper, word timestamps) and offsets the
// words by the clip's data-start in index.html. Run AFTER changing
// scripts/generate-vo.sh output or any VO data-start in index.html:
//
//   node scripts/generate-captions.mjs
//
// The output file is committed (CI renders don't run whisper). The
// OFFSETS below must match the <audio> data-start values in index.html.
import { execSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";

const OFFSETS = {
  "01-hook": 0.2,
  "02-brand": 3.6,
  "03-dashboard": 5.9,
  "04-preferences": 13.9,
  "05-ats": 21.4,
  "06-recommended": 32.4,
  "07-extension": 40.0,
  "08-stats": 47.9,
  "09-cta": 53.7,
};

const words = [];
for (const [name, offset] of Object.entries(OFFSETS)) {
  console.log(`transcribing ${name}…`);
  execSync(`npx --yes hyperframes@0.6.91 transcribe assets/vo/${name}.wav --json`, {
    stdio: ["ignore", "ignore", "inherit"],
  });
  const clipWords = JSON.parse(readFileSync("assets/vo/transcript.json", "utf8"));
  for (const w of clipWords) {
    words.push({
      text: w.text,
      start: +(w.start + offset).toFixed(2),
      end: +(w.end + offset).toFixed(2),
    });
  }
}

// Group into chunks: break on punctuation, speech gap > 0.45s, or 3 words.
const groups = [];
let g = null;
words.forEach((w, i) => {
  const prev = words[i - 1];
  const breakBefore =
    !g ||
    g[1] - g[0] >= 2 ||
    (prev && w.start - prev.end > 0.45) ||
    (prev && /[.!?—]$/.test(prev.text));
  if (breakBefore) {
    g = [i, i];
    groups.push(g);
  } else {
    g[1] = i;
  }
});

const banner =
  "// GENERATED by scripts/generate-captions.mjs — do not edit by hand.\n" +
  "// Word timings are whisper transcripts of assets/vo/*.wav offset by\n" +
  "// the <audio> data-start values in index.html.\n";
writeFileSync(
  "assets/captions-data.js",
  banner +
    "window.__captionWords = " + JSON.stringify(words) + ";\n" +
    "window.__captionGroups = " + JSON.stringify(groups) + ";\n",
);
console.log(`wrote assets/captions-data.js — ${words.length} words, ${groups.length} groups`);
